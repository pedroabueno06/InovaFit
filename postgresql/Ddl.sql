-- InovaFit
-- Sistema de academia, onde é possível realizar o gerenciamento dos alunos
-- que estão matriculados na academia, gerenciar os planos de matrícula, pagamentos e entre outros.
-- Além de que as constraints estão sempre com nomes de pk_, uk_ e etc.
-- Diferenças entre PostgreSQL e Oracle:
-- VARCHAR no lugar de VARCHAR2;
-- CURRENT_DATE NO LUGAR DE TRUNC(SYSDATE);
-- EXPLAIN ANALYZE NO LUGAR DE EXPLAIN PLAN.

DROP TABLE IF EXISTS auditoria,matricula,frequencia,pagamento,matricula_modalidade,matricula,modalidade,plano,aluno CASCADE;

CREATE TABLE aluno (
    id_aluno BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_aluno PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL CONSTRAINT uk_aluno_email UNIQUE,
    data_nascimento DATE NOT NULL,
    data_cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_aluno_nome CHECK (length(trim(nome)) >= 3)
);

CREATE TABLE plano (
    id_plano BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_plano PRIMARY KEY,
    nome VARCHAR(60) NOT NULL CONSTRAINT uk_plano_nome UNIQUE,
    valor_mensal NUMERIC(10,2) NOT NULL,
    duracao_meses INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_plano_valor CHECK (valor_mensal > 0),
    CONSTRAINT ck_plano_duracao CHECK (duracao_meses BETWEEN 1 AND 24)
);

CREATE TABLE modalidade (
    id_modalidade BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_modalidade PRIMARY KEY,
    nome VARCHAR(60) NOT NULL CONSTRAINT uk_modalidade_nome UNIQUE,
    descricao VARCHAR(200),
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE matricula (
    id_matricula BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_matricula PRIMARY KEY,
    id_aluno BIGINT NOT NULL,
    id_plano BIGINT NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVA',
    bloqueada BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_matricula_aluno FOREIGN KEY (id_aluno) REFERENCES aluno(id_aluno) ON DELETE RESTRICT,
    CONSTRAINT fk_matricula_plano FOREIGN KEY (id_plano) REFERENCES plano(id_plano) ON DELETE RESTRICT,
    CONSTRAINT ck_matricula_status CHECK (status IN ('ATIVA','CANCELADA','ENCERRADA')),
    CONSTRAINT ck_matricula_datas CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE UNIQUE INDEX uk_matricula_ativa_aluno ON matricula(id_aluno) WHERE status = 'ATIVA';
CREATE TABLE matricula_modalidade (
    id_matricula_modalidade BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_matricula_modalidade PRIMARY KEY,
    id_matricula BIGINT NOT NULL,
    id_modalidade BIGINT NOT NULL,
    data_inclusao DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_mm_matricula FOREIGN KEY (id_matricula) REFERENCES matricula(id_matricula) ON DELETE CASCADE,
    CONSTRAINT fk_mm_modalidade FOREIGN KEY (id_modalidade) REFERENCES modalidade(id_modalidade) ON DELETE RESTRICT,
    CONSTRAINT uk_matricula_modalidade UNIQUE (id_matricula,id_modalidade)
);

CREATE TABLE pagamento (
    id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_pagamento PRIMARY KEY,
    id_matricula BIGINT NOT NULL,
    competencia DATE NOT NULL,
    vencimento DATE NOT NULL,
    data_pagamento DATE,
    valor NUMERIC(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    CONSTRAINT fk_pagamento_matricula FOREIGN KEY (id_matricula) REFERENCES matricula(id_matricula) ON DELETE RESTRICT,
    CONSTRAINT uk_pagamento_competencia UNIQUE (id_matricula,competencia),
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0),
    CONSTRAINT ck_pagamento_status CHECK (status IN ('PENDENTE','PAGO','ATRASADO'))
);

CREATE TABLE frequencia (
    id_frequencia BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_frequencia PRIMARY KEY,
    id_matricula BIGINT NOT NULL,
    data_hora_entrada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_frequencia_matricula FOREIGN KEY (id_matricula) REFERENCES matricula(id_matricula) ON DELETE RESTRICT
);

CREATE TABLE auditoria_matricula (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_auditoria_matricula PRIMARY KEY,
    id_matricula BIGINT NOT NULL,
    status_anterior VARCHAR(20) NOT NULL,
    status_novo VARCHAR(20) NOT NULL,
    data_evento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_auditoria_matricula FOREIGN KEY (id_matricula) REFERENCES matricula(id_matricula) ON DELETE RESTRICT
);