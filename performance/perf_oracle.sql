
CREATE TABLE plano (
    id_plano NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_plano_perf PRIMARY KEY,
    nome VARCHAR2(60) NOT NULL,
    valor_mensal NUMBER(10,2) NOT NULL,
    duracao_meses NUMBER(3) NOT NULL,
    ativo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT uk_plano_nome_perf UNIQUE(nome),
    CONSTRAINT ck_plano_valor_perf CHECK(valor_mensal > 0),
    CONSTRAINT ck_plano_duracao_perf CHECK(duracao_meses BETWEEN 1 AND 24),
    CONSTRAINT ck_plano_ativo_perf CHECK(ativo IN(0,1))
);

CREATE TABLE aluno (
    id_aluno NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_aluno_perf PRIMARY KEY,
    nome VARCHAR2(120) NOT NULL,
    email VARCHAR2(160) NOT NULL,
    data_nascimento DATE NOT NULL,
    data_cadastro DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    CONSTRAINT uk_aluno_email_perf UNIQUE(email),
    CONSTRAINT ck_aluno_nome_perf CHECK(LENGTH(TRIM(nome)) >= 3)
);

CREATE TABLE matricula (
    id_matricula NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_matricula_perf PRIMARY KEY,
    id_aluno NUMBER NOT NULL,
    id_plano NUMBER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    status VARCHAR2(20) DEFAULT 'ATIVA' NOT NULL,
    bloqueada NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_matricula_aluno_perf FOREIGN KEY(id_aluno) REFERENCES aluno(id_aluno),
    CONSTRAINT fk_matricula_plano_perf FOREIGN KEY(id_plano) REFERENCES plano(id_plano),
    CONSTRAINT ck_matricula_status_perf CHECK(status IN('ATIVA','CANCELADA','ENCERRADA')),
    CONSTRAINT ck_matricula_datas_perf CHECK(data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT ck_matricula_bloqueada_perf CHECK(bloqueada IN(0,1))
);

CREATE TABLE pagamento (
    id_pagamento NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_pagamento_perf PRIMARY KEY,
    id_matricula NUMBER NOT NULL,
    competencia DATE NOT NULL,
    vencimento DATE NOT NULL,
    data_pagamento DATE,
    valor NUMBER(10,2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
    CONSTRAINT fk_pagamento_matricula_perf FOREIGN KEY(id_matricula) REFERENCES matricula(id_matricula),
    CONSTRAINT ck_pagamento_valor_perf CHECK(valor > 0),
    CONSTRAINT ck_pagamento_status_perf CHECK(status IN('PENDENTE','PAGO','ATRASADO'))
);

