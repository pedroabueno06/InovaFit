-- ============================================================
-- performance/perf_postgresql_schema.sql
--
-- Cria o schema isolado "performance" e as tabelas utilizadas
-- pela massa de dados de desempenho do InovaFit.
--
-- Objetivos:
--   * Isolar a carga de dezenas de milhares de registros dos
--     dados principais (schema public);
--   * Permitir medir planos "antes" e "depois" dos índices sem
--     interferir nas tabelas, índices e dados principais;
--   * Espelhar a estrutura da DDL principal (postgresql/ddl.sql)
--     em produção, com EXCEÇÕES deliberadas e restritas a este
--     schema, detalhadas abaixo.
--
-- EXCEÇÕES AO ESPELHO DA DDL PRINCIPAL (somente schema performance):
--
--   1) A CONSTRAINT ÚNICA uk_pagamento_competencia(id_matricula,
--      competencia) foi OMITIDA (PAGAMENTO estava sem o UNIQUE).
--   2) O ÍNDICE ÚNICO PARCIAL uk_matricula_ativa_aluno(id_aluno)
--      WHERE status = 'ATIVA' foi OMITIDO.
--
--   Motivo único e exclusivo: essas duas restrições criariam
--   índices com id_matricula e id_aluno como coluna/prefixo líder,
--   tornando redundantes os índices de FK do experimento
--   (pagamento(id_matricula) e matricula(id_aluno)) e mascarando
--   o efeito real dos índices que se deseja demonstrar.
--
--   MANTIDOS INTACTOS: chaves primárias, FKs, índice único
--   aluno(email) e todas as demais estruturas. O SCHEMA PRINCIPAL
--   (public) NÃO é alterado em hipótese alguma.
--
--   Tabelas também omitidas por não serem necessárias às duas
--   consultas de desempenho: modalidade, auditoria_matricula,
--   frequencia.
--
-- Execução:
--   * Manual, como o usuário "inovafit" (dono do schema).
--   * NÃO deve ser registrado no docker-entrypoint-initdb.d.
--
-- Segurança:
--   * Este script NÃO remove nem altera objetos existentes.
--   * Apenas cria o schema e as tabelas perf.
--   * Para descartar a estrutura por completo (dados fictícios
--     somente), utilizar performance/perf_reset.sql, que também
--     só pode ser executado com autorização explícita.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS performance;

-- ------------------------------------------------------------
-- Plano (necessário para a matrícula no plano 'Mensal')
-- ------------------------------------------------------------
CREATE TABLE performance.plano (
    id_plano BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_plano_perf PRIMARY KEY,
    nome VARCHAR(60) NOT NULL CONSTRAINT uk_plano_nome_perf UNIQUE,
    valor_mensal NUMERIC(10,2) NOT NULL,
    duracao_meses INTEGER NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_plano_valor_perf CHECK (valor_mensal > 0),
    CONSTRAINT ck_plano_duracao_perf CHECK (duracao_meses BETWEEN 1 AND 24)
);

-- ------------------------------------------------------------
-- Aluno (índice único de e-mail MANTIDO: necessário à Consulta 1)
-- ------------------------------------------------------------
CREATE TABLE performance.aluno (
    id_aluno BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_aluno_perf PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL CONSTRAINT uk_aluno_email_perf UNIQUE,
    data_nascimento DATE NOT NULL,
    data_cadastro DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT ck_aluno_nome_perf CHECK (length(trim(nome)) >= 3)
);

-- ------------------------------------------------------------
-- Matrícula
-- O índice único parcial uk_matricula_ativa_aluno foi OMITIDO
-- neste schema (ver justificativa no cabeçalho).
-- ------------------------------------------------------------
CREATE TABLE performance.matricula (
    id_matricula BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_matricula_perf PRIMARY KEY,
    id_aluno BIGINT NOT NULL,
    id_plano BIGINT NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ATIVA',
    bloqueada BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_matricula_aluno_perf FOREIGN KEY (id_aluno) REFERENCES performance.aluno(id_aluno) ON DELETE RESTRICT,
    CONSTRAINT fk_matricula_plano_perf FOREIGN KEY (id_plano) REFERENCES performance.plano(id_plano) ON DELETE RESTRICT,
    CONSTRAINT ck_matricula_status_perf CHECK (status IN ('ATIVA','CANCELADA','ENCERRADA')),
    CONSTRAINT ck_matricula_datas_perf CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

-- ------------------------------------------------------------
-- Pagamento
-- A constraint única uk_pagamento_competencia(id_matricula,
-- competencia) foi OMITIDA neste schema (ver justificativa no
-- cabeçalho). Ela voltará a existir apenas no schema principal.
-- ------------------------------------------------------------
CREATE TABLE performance.pagamento (
    id_pagamento BIGINT GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_pagamento_perf PRIMARY KEY,
    id_matricula BIGINT NOT NULL,
    competencia DATE NOT NULL,
    vencimento DATE NOT NULL,
    data_pagamento DATE,
    valor NUMERIC(10,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    CONSTRAINT fk_pagamento_matricula_perf FOREIGN KEY (id_matricula) REFERENCES performance.matricula(id_matricula) ON DELETE RESTRICT,
    CONSTRAINT ck_pagamento_valor_perf CHECK (valor > 0),
    CONSTRAINT ck_pagamento_status_perf CHECK (status IN ('PENDENTE','PAGO','ATRASADO'))
);

-- ------------------------------------------------------------
-- Plano exigido pela carga de desempenho (plano 'Mensal')
-- ------------------------------------------------------------
INSERT INTO performance.plano (nome, valor_mensal, duracao_meses)
VALUES ('Mensal', 120, 1);
