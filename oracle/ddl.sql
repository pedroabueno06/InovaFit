CREATE TABLE aluno(
    id_aluno NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_aluno PRIMARY KEY,
    nome VARCHAR2(120) NOT NULL,
    email VARCHAR2(160) NOT NULL,
    data_nascimento DATE NOT NULL,
    data_cadastro DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    CONSTRAINT uk_aluno_email UNIQUE(email),
    CONSTRAINT ck_aluno_nome CHECK(LENGTH(TRIM(nome))>=3)
);

CREATE TABLE plano(
    id_plano NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_plano PRIMARY KEY,
    nome VARCHAR2(60) NOT NULL,
    valor_mensal NUMBER(10,2) NOT NULL,
    duracao_meses number(3) NOT NULL,
    ativo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT uk_plano_nome UNIQUE(nome),
    CONSTRAINT ck_plano_valor CHECK(valor_mensal>0),
    CONSTRAINT ck_plano_duracao CHECK(duracao_meses BETWEEN 1 AND 24),
    CONSTRAINT ck_plano_ativo CHECK(ativo IN(0,1))
);

CREATE TABLE modalidade(
    id_modalidade NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_modalidade PRIMARY KEY,
    nome VARCHAR2(60) NOT NULL,
    descricao VARCHAR2(200),
    ativa NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT uk_modalidade_nome UNIQUE(nome),
    CONSTRAINT ck_modalidade_ativa CHECK(ativa IN(0,1))
);

CREATE TABLE matricula(
    id_matricula NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_matricula PRIMARY KEY,
    id_aluno NUMBER NOT NULL,
    id_plano NUMBER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE,
    status VARCHAR2(20) DEFAULT 'ATIVA' NOT NULL,
    bloqueada NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_matricula_aluno FOREIGN KEY(id_aluno) REFERENCES aluno(id_aluno),
    CONSTRAINT fk_matricula_plano FOREIGN KEY(id_plano) REFERENCES plano(id_plano),
    CONSTRAINT ck_matricula_status CHECK(status IN('ATIVA','CANCELADA','ENCERRADA')),
    CONSTRAINT ck_matricula_datas CHECK(data_fim IS NULL OR data_fim>=data_inicio),
    CONSTRAINT ck_matricula_bloqueada CHECK(bloqueada IN(0,1))
);

CREATE TABLE matricula_modalidade(
    id_matricula_modalidade NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_matricula_modalidade PRIMARY KEY,
    id_matricula NUMBER NOT NULL,
    id_modalidade NUMBER NOT NULL,
    data_inclusao DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    CONSTRAINT fk_mm_matricula FOREIGN KEY(id_matricula) REFERENCES matricula(id_matricula) ON DELETE CASCADE,
    CONSTRAINT fk_mm_modalidade FOREIGN KEY(id_modalidade) REFERENCES modalidade(id_modalidade),
    CONSTRAINT uk_matricula_modalidade UNIQUE(id_matricula,id_modalidade)
);

CREATE TABLE pagamento(
    id_pagamento NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_pagamento PRIMARY KEY,
    id_matricula NUMBER NOT NULL,
    competencia DATE NOT NULL,
    vencimento DATE NOT NULL,
    data_pagamento DATE,
    valor NUMBER(10,2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'PENDENTE' NOT NULL,
    CONSTRAINT fk_pagamento_matricula FOREIGN KEY(id_matricula) REFERENCES matricula(id_matricula),
    CONSTRAINT uk_pagamento_competencia UNIQUE(id_matricula,competencia),
    CONSTRAINT ck_pagamento_valor CHECK(valor>0),
    CONSTRAINT ck_pagamento_status CHECK(status IN('PENDENTE','PAGO','ATRASADO'))
);

CREATE TABLE frequencia(
    id_frequencia NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_frequencia PRIMARY KEY,
    id_matricula NUMBER NOT NULL,
    data_hora_entrada TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_frequencia_matricula FOREIGN KEY(id_matricula) REFERENCES matricula(id_matricula)
);

CREATE TABLE auditoria_matricula(
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_auditoria_matricula PRIMARY KEY,
    id_matricula NUMBER NOT NULL,
    status_anterior VARCHAR2(20) NOT NULL,
    status_novo VARCHAR2(20) NOT NULL,
    data_evento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_auditoria_matricula FOREIGN KEY(id_matricula) REFERENCES matricula(id_matricula)
);

CREATE UNIQUE INDEX uk_matricula_ativa_aluno ON matricula(CASE WHEN status='ATIVA' THEN id_aluno END);